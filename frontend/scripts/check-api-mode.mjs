// API mode against a mocked API: RTI draft preview (rules, notes, address line breaks), Copy (plain text to the
// clipboard), Download (.txt), and the Live wind badge. Build with the API URL set, serve it, then run:
//   VITE_API_URL=http://api.mock npx vite build --outDir dist-api && npx vite preview --outDir dist-api --port 4176
//   node scripts/check-api-mode.mjs [baseUrl]
import { readFileSync } from 'node:fs'
import { chromium } from 'playwright'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
const base = process.argv[2] ?? 'http://localhost:4176'
const DATA = resolve(dirname(fileURLToPath(import.meta.url)), '../public/data') + '/'
const out = resolve(dirname(fileURLToPath(import.meta.url)), '../../docs/reference/screens')
const json = (f) => JSON.parse(readFileSync(DATA + f, 'utf8'))
// Same shape as api/handlers/rti.py output (two boards, a note, address lines, a rule, the footer).
const md = ['# Draft RTI application: Singrauli cluster', '', '> One application per board.', '', '## Application to the Madhya Pradesh Pollution Control Board', '', 'To,  ', 'The Public Information Officer,  ', '[Address of the Public Information Officer]  ', '', '**Periods:**', '', '- 2 Feb 2026 to 21 Aug 2026', '', '1. Inspection reports', '2. OCEMS records', '', '---', '', '## Application to the Uttar Pradesh Pollution Control Board', '', 'Sir/Madam,', '', '---', '', '_Draft generated by PanoptiCoal. Not legal advice._', ''].join('\n')
const rti = { markdown: md, plain_text: md.replace(/[*_#>]/g, '') }
const b = await chromium.launch({ channel: 'chrome' })
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true, permissions: ['clipboard-read', 'clipboard-write'] })
await ctx.addInitScript(() => { localStorage.setItem('pc-hold-seen', '1'); localStorage.setItem('pc-sound', 'off') })
await ctx.route('http://api.mock/**', async (route) => {
  const u = new URL(route.request().url()), p = u.pathname
  let body
  if (p === '/clusters') body = json('clusters.json')
  else if (p === '/summary') body = json('summary.json')
  else if (p === '/plants') body = json('plants_india.json')
  else if (p === '/states') body = json('states.json')
  else if (/^\/clusters\/[\w-]+\/timeseries$/.test(p)) body = json(`timeseries_${p.split('/')[2]}.json`)
  else if (/^\/clusters\/[\w-]+\/wind$/.test(p)) body = { ...json(`wind_${p.split('/')[2]}.json`).trace, source: 'live' }
  else if (/^\/clusters\/[\w-]+$/.test(p)) body = json(`cluster_${p.split('/')[2]}.json`)
  else if (p.startsWith('/rti/')) body = rti
  if (!body) return route.fulfill({ status: 404, body: '{}' })
  return route.fulfill({ status: 200, contentType: 'application/json', headers: { 'access-control-allow-origin': '*' }, body: JSON.stringify(body) })
})
const page = await ctx.newPage()
const errs = []
page.on('pageerror', (e) => errs.push(e.message))
await page.goto(base + '/cluster/singrauli', { waitUntil: 'networkidle' })
await page.click('text=Inspection brief & RTI draft')
await page.waitForTimeout(800)
await page.click('text=Draft an RTI request')
await page.waitForSelector('.rti-doc', { timeout: 5000 })
const r = await page.evaluate(() => ({ hr: document.querySelectorAll('.rti-doc hr').length, bq: document.querySelectorAll('.rti-doc blockquote').length, br: document.querySelectorAll('.rti-doc br').length, legal: document.querySelector('.rti-legal')?.textContent, h3: [...document.querySelectorAll('.rti-doc h3')].map((h) => h.textContent).slice(0, 4) }))
console.log('preview', JSON.stringify(r))
await page.click('text=Copy text')
await page.waitForTimeout(300)
const clip = await page.evaluate(() => navigator.clipboard.readText())
console.log('copied plain text', clip.replace(/\r\n/g, '\n') === rti.plain_text, clip.length) // the Windows clipboard uses CRLF
const [dl] = await Promise.all([page.waitForEvent('download'), page.click('text=Download .txt')])
console.log('download', dl.suggestedFilename())
await page.evaluate(() => document.querySelector('.rti-doc')?.scrollIntoView({ block: 'start' }))
await page.waitForTimeout(700)
await page.screenshot({ path: out + '/rti-draft-api.png' })
await page.goto(base + '/map', { waitUntil: 'networkidle' })
await page.waitForSelector('.wind-src', { timeout: 8000 })
console.log('wind badge', await page.textContent('.wind-src'))
console.log('errors', errs)
await b.close()
